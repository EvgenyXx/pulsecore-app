package ru.pulsecore.app.shared.api.tournament;

/**
 * Контракт управления планировщиком турниров из админ-панели.
 * <p>
 * Позволяет ставить фоновые задачи на паузу, возобновлять их,
 * проверять статус, а также принудительно запускать любые задачи шедулера
 * (проверка старта, поиск новых, обработка завершенных и т.д.) по требованию.
 */
public interface SchedulerAdminClient {

    // ================= Управление состоянием =================

    /**
     * Ставит планировщик на паузу (фоновые задачи перестают выполняться).
     */
    void pauseScheduler();

    /**
     * Возобновляет работу планировщика после паузы.
     */
    void resumeScheduler();

    /**
     * Проверяет, находится ли планировщик на паузе.
     *
     * @return {@code true}, если на паузе, иначе {@code false}.
     */
    boolean isSchedulerPaused();

    // ================= Принудительный запуск задач =================

    /**
     * Принудительно запускает задачу проверки старта турниров.
     */
    void checkStart();

    /**
     * Принудительно запускает задачу обработки завершенных турниров.
     */
    void processFinishedTournaments();

    /**
     * Принудительно запускает задачу поиска новых турниров.
     */
    void checkNewTournaments();

    /**
     * Принудительно запускает задачу проверки изменений в расписании турниров.
     */
    void checkChangedTournament();

    /**
     * Принудительно запускает задачу обработки отмененных турниров.
     */
    void checkCanceled();
}